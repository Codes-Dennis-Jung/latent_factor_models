def build(execute: bool, timeout: int = 900) -> None:
    for name, cells in NOTEBOOKS.items():
        nb = nbf.v4.new_notebook()
        nb.cells = cells
        nb.metadata["kernelspec"] = {
            "name": "python3",
            "display_name": "Python 3",
            "language": "python",
        }
        nb.metadata["language_info"] = {"name": "python"}
        path = HERE / f"{name}.ipynb"
        if execute:
            from nbclient import NotebookClient

            NotebookClient(
                nb,
                timeout=timeout,
                kernel_name="python3",
                resources={"metadata": {"path": str(HERE)}},
            ).execute()
        nbf.write(nb, path)
        _ruff(path)
        print(f"wrote {path.name}" + (" (executed)" if execute else ""))


def _ruff(path: Path) -> None:
    """Sort imports and format code cells with ruff (if installed); outputs are untouched."""
    import shutil
    import subprocess

    exe = shutil.which("ruff") or str(Path(sys.executable).with_name("ruff"))
    try:
        subprocess.run([exe, "check", "--fix", "--select", "I,E401", "-q", str(path)], check=False)
        subprocess.run([exe, "format", "-q", str(path)], check=False)
    except OSError:
        pass


def _use_this_interpreter_as_kernel() -> None:
    """Point the 'python3' kernel at sys.executable (JUPYTER_PATH has priority)."""
    root = Path(tempfile.mkdtemp())
    spec_dir = root / "kernels" / "python3"
    spec_dir.mkdir(parents=True)
    spec = {
        "argv": [sys.executable, "-m", "ipykernel_launcher", "-f", "{connection_file}"],
        "display_name": "Python 3",
        "language": "python",
    }
    (spec_dir / "kernel.json").write_text(json.dumps(spec))
    os.environ["JUPYTER_PATH"] = str(root) + os.pathsep + os.environ.get("JUPYTER_PATH", "")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--execute", action="store_true", help="execute and store outputs")
    args = parser.parse_args()
    if args.execute:
        _use_this_interpreter_as_kernel()
    build(args.execute)
